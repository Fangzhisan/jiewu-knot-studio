export const KNOT_REVIEW_CHECKS: readonly KnotReviewCheck[] = [
  'actions',
  'routing',
  'turns',
  'finishing',
  'tightening',
  'finished-shape',
  'browser',
];

type Review = Pick<KnotProduction, 'review' | 'note' | 'checks'>;

/** 编译时要求七项依据齐全；这里只记录动画检查，不代替实物工艺验证。 */
function passed(note: string, notes: Record<KnotReviewCheck, string>): Review {
  return {
    review: 'passed',
    note,
    checks: Object.fromEntries(
      KNOT_REVIEW_CHECKS.map((key) => [key, { status: 'passed', note: notes[key] }]),
    ) as Record<KnotReviewCheck, KnotReviewResult>,
  };
}

